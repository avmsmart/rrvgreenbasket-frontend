export function getPackingDataByDate(targetDate: string = "26 Oct 2026"): {
  orders: PackingOrder[];
  summary: PackingSummary;
  topProducts: TopPackingProduct[];
  activities: PackingActivity[];
} {
  const systemToday = getSystemDateFormatted();
  const systemYesterday = getOffsetDateFormatted(-1);
  const isToday =
    targetDate.includes("26 Oct") ||
    targetDate.includes("25 Aug") ||
    targetDate.toLowerCase().includes("today") ||
    targetDate === systemToday;
  const isYesterday =
    targetDate.includes("25 Oct") ||
    targetDate.includes("24 Aug") ||
    targetDate.toLowerCase().includes("yesterday") ||
    targetDate === systemYesterday;

  let orders = [...MOCK_PACKING_ORDERS_PAGE13];

  if (isYesterday) {
    // Yesterday: all orders packed & dispatched
    orders = orders.map((o) => ({
      ...o,
      orderDate: targetDate,
      status: "Packed",
      items: o.items.map((it) => ({ ...it, isPacked: true })),
    }));
  } else if (!isToday) {
    // Historical past date: all packed
    orders = orders.map((o) => ({
      ...o,
      orderDate: targetDate,
      status: "Packed",
      items: o.items.map((it) => ({ ...it, isPacked: true })),
    }));
  } else {
    // Today
    orders = orders.map((o) => ({
      ...o,
      orderDate: targetDate,
    }));
  }

  const totalOrdersToPack = orders.length;
  const pending = orders.filter((o) => o.status === "Pending").length;
  const inPacking = orders.filter((o) => o.status === "In Packing").length;
  const packed = orders.filter((o) => o.status === "Packed").length;

  let totalItemsCount = 0;
  let packedItemsCount = 0;
  orders.forEach((o) => {
    totalItemsCount += o.items.length;
    packedItemsCount += o.items.filter((it) => it.isPacked).length;
  });

  const packingPercentage =
    totalItemsCount > 0 ? Math.round((packedItemsCount / totalItemsCount) * 100) : 57;

  const summary: PackingSummary = {
    totalOrdersToPack,
    pending,
    inPacking,
    packed,
    packingPercentage: isYesterday ? 100 : packingPercentage,
    packedOrdersCount: packed + 10,
  };

  return {
    orders,
    summary,
    topProducts: MOCK_TOP_PACKING_PRODUCTS,
    activities: MOCK_PACKING_ACTIVITIES,
  };
}
