/**
 * Converts CustomerDetailResponse to CustomerListItem for table listings
 */
export function toCustomerListItem(detail: CustomerDetailResponse): CustomerListItem {
  const primaryAddress = detail.addresses.find((a) => a.isDefault) || detail.addresses[0];
  const location = primaryAddress
    ? `${primaryAddress.city}, ${primaryAddress.pincode}`
    : "Kurnool, 518002";

  return {
    id: detail.id,
    fullName: detail.fullName,
    email: detail.email,
    mobileNumber: detail.mobileNumber,
    profileImageUrl: detail.profileImageUrl,
    status: detail.status,
    location,
    totalOrders: detail.statistics.totalOrders,
    totalSpent: detail.statistics.totalSpent,
    createdAt: detail.createdAt,
  };
}

